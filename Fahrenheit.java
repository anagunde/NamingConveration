// Write a program to convert temperature from celsius to fahrenheit using the formula.


public class Fahrenheit {
	 public static void main(String args[])   
	 {                                                     
	    float  D=25;
	    System.out.println("Fahrenheit = "+(D*9)/5+32);
	    }
}
  // Output :- 45.032
                                             //Formula :-  °F = (°C × 9/5) + 32. 



